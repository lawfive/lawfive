import { type MisconductScheme, misconductSchemes } from "./misconduct.ts";

// EVT-14: the card's reason on the watch. Each watch app builds in the codes as short rows (the code
// and a few words), written here from schema/misconduct/ by `pnpm generate` rather than copied by hand.
// A send-off's list leaves out the second caution's code: the watch records a second caution as one.
// A scheme the watch doesn't know (one added after its build) is listed as IFAB's, and the match records
// the scheme its list came from.

const header = "Generated by schema/scripts/generate.ts from schema/misconduct/*.json (EVT-14): don't edit; run pnpm generate.";
const fallback = "ifab";

type Row = [code: string, meaning: string];

function rows(scheme: MisconductScheme, sendOff: boolean): Row[] {
    const list = sendOff ? scheme.sendOffs.filter((c) => c.code !== scheme.secondCaution) : scheme.cautions;
    return list.map((c) => [c.code, c.short ?? (c.description.length > 22 ? `${c.description.slice(0, 21).trimEnd()}…` : c.description)]);
}

const ids = () => Object.keys(misconductSchemes).sort();
const literal = (text: string) => JSON.stringify(text);

function monkeyC(): string {
    const known = ids().map((id) => `scheme.equals(${literal(id)})`).join(" || ");
    const lists = (id: string, indent: string) => {
        const list = (sendOff: boolean) => `[${rows(misconductSchemes[id]!, sendOff).flat().map(literal).join(", ")}]`;
        return `(sendOff\n${indent}    ? ${list(true)}\n${indent}    : ${list(false)}) as Array<String>`;
    };
    const branches = ids().filter((id) => id !== fallback).map((id) => `    if (scheme.equals(${literal(id)})) {\n        return ${lists(id, "        ")};\n    }\n`).join("");
    return `//! ${header}

import Toybox.Lang;

//! EVT-14: the scheme a match's card reasons are listed from: the one given when the watch knows it, else IFAB's.
function misconductScheme(scheme as String?) as String {
    if (scheme != null && (${known})) {
        return scheme;
    }
    return ${literal(fallback)};
}

//! EVT-14: a scheme's codes for a caution (sendOff false) or a send-off (true; without the second caution's),
//! as code and meaning in turn: ["UB", "Unsporting behavior", "DT", "Dissent", ...].
function misconductCodes(scheme as String, sendOff as Boolean) as Array<String> {
${branches}    return ${lists(fallback, "    ")};
}
`;
}

function kotlin(): string {
    const name = (id: string, sendOff: boolean) => `${id.toUpperCase().replace(/-/g, "_")}_${sendOff ? "SEND_OFFS" : "CAUTIONS"}`;
    const lists = ids().flatMap((id) => [false, true].map((sendOff) =>
        `    private val ${name(id, sendOff)} = listOf(${rows(misconductSchemes[id]!, sendOff).map(([code, meaning]) => `${literal(code)} to ${literal(meaning)}`).join(", ")})\n`)).join("");
    const branches = ids().map((id) => `        ${literal(id)} -> if (sendOff) ${name(id, true)} else ${name(id, false)}\n`).join("");
    return `// ${header}

package app.lawfive.wear

/** EVT-14: the misconduct codes for the card's reason, as code and a few words. */
object Misconduct {
    private val known = setOf(${ids().map(literal).join(", ")})

    /** The scheme a match's reasons are listed from: the one given when the watch knows it, else IFAB's. */
    fun scheme(id: String?): String = if (id != null && id in known) id else ${literal(fallback)}

    /** A scheme's codes for a caution or (sendOff) a send-off, without the second caution's. */
    fun codes(scheme: String, sendOff: Boolean): List<Pair<String, String>> = when (scheme(scheme)) {
${branches}        else -> if (sendOff) ${name(fallback, true)} else ${name(fallback, false)}
    }

${lists}}
`;
}

function swift(): string {
    const list = (id: string, sendOff: boolean) => `[${rows(misconductSchemes[id]!, sendOff).map(([code, meaning]) => `(${literal(code)}, ${literal(meaning)})`).join(", ")}]`;
    const branches = ids().map((id) => `        case ${literal(id)}: return sendOff ? ${list(id, true)} : ${list(id, false)}\n`).join("");
    return `// ${header}

/// EVT-14: the misconduct codes for the card's reason, as code and a few words.
enum Misconduct {
    static let known: Set<String> = [${ids().map(literal).join(", ")}]

    /// The scheme a match's reasons are listed from: the one given when the watch knows it, else IFAB's.
    static func scheme(_ id: String?) -> String {
        if let id, known.contains(id) { return id }
        return ${literal(fallback)}
    }

    /// A scheme's codes for a caution or (sendOff) a send-off, without the second caution's.
    static func codes(_ scheme: String, sendOff: Bool) -> [(code: String, meaning: String)] {
        switch Misconduct.scheme(scheme) {
${branches}        default: return []
        }
    }
}
`;
}

/** The watches' copies, by path from schema/. */
export function misconductFiles(): Record<string, string> {
    return {
        "../watch-garmin/source/Misconduct.mc": monkeyC(),
        "../mobile/android/wear/src/main/java/app/lawfive/wear/Misconduct.kt": kotlin(),
        "../mobile/ios/LawFiveWatch/Misconduct.swift": swift(),
    };
}
